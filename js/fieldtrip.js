/* ---------- 座標換算：WGS84 經緯度 ↔ TWD97 TM2（中央經線 121°） ---------- */
FN.geo = (function () {
  var a = 6378137, f = 1 / 298.257222101, e2 = f * (2 - f), k0 = 0.9999, lon0 = 121 * Math.PI / 180, dx = 250000;
  var ep2 = e2 / (1 - e2);
  function M(lat) {
    return a * ((1 - e2 / 4 - 3 * e2 * e2 / 64 - 5 * e2 * e2 * e2 / 256) * lat - (3 * e2 / 8 + 3 * e2 * e2 / 32 + 45 * e2 * e2 * e2 / 1024) * Math.sin(2 * lat) +
      (15 * e2 * e2 / 256 + 45 * e2 * e2 * e2 / 1024) * Math.sin(4 * lat) - (35 * e2 * e2 * e2 / 3072) * Math.sin(6 * lat));
  }
  function toTWD97(latDeg, lonDeg) {
    var lat = latDeg * Math.PI / 180, lon = lonDeg * Math.PI / 180;
    var N = a / Math.sqrt(1 - e2 * Math.sin(lat) * Math.sin(lat)), T = Math.tan(lat) * Math.tan(lat), C = ep2 * Math.cos(lat) * Math.cos(lat), A = (lon - lon0) * Math.cos(lat);
    var x = k0 * N * (A + (1 - T + C) * Math.pow(A, 3) / 6 + (5 - 18 * T + T * T + 72 * C - 58 * ep2) * Math.pow(A, 5) / 120);
    var y = k0 * (M(lat) + N * Math.tan(lat) * (A * A / 2 + (5 - T + 9 * C + 4 * C * C) * Math.pow(A, 4) / 24 + (61 - 58 * T + T * T + 600 * C - 330 * ep2) * Math.pow(A, 6) / 720));
    return { E: x + dx, N: y };
  }
  function unitAt(E, N) {
    var g = FN.GEO_GRID, i = Math.floor((E - g.E0) / g.cell), j = Math.floor((g.N0 - N) / g.cell);
    if (j < 0 || j >= g.rows.length || i < 0 || i >= g.rows[0].length) return null;
    var c = Number(g.rows[j][i]);
    /* 是否靠近地層界線（20 m 內有不同代碼） */
    var edge = false;
    for (var dj = -2; dj <= 2 && !edge; dj++) for (var di = -2; di <= 2; di++) {
      var r = g.rows[j + dj]; if (r && r[i + di] !== undefined && Number(r[i + di]) !== c) { edge = true; break; }
    }
    return { unit: FN.GEO_UNITS[c], code: c, edge: edge };
  }
  function dist(E1, N1, E2, N2) { return Math.hypot(E2 - E1, N2 - N1); }
  function bearing(E1, N1, E2, N2) { return (Math.atan2(E2 - E1, N2 - N1) * 180 / Math.PI + 360) % 360; }
  function inArea(E, N) { var L = FN.MAP_LAYERS[0]; return E >= L.west && E <= L.east && N >= L.south && N <= L.north; }
  return { toTWD97: toTWD97, unitAt: unitAt, dist: dist, bearing: bearing, inArea: inArea };
})();

